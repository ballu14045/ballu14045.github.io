import os
from datetime import datetime

article_title = "Prabaha: Automated News Live"
article_text = "This is the first automated Odia news post generated by our local AI pipeline."
image_url = "https://example.com/sample-image.jpg"

today_date = datetime.now().strftime('%Y-%m-%d')
filename = f"_posts/{today_date}-prabaha-live.md"

markdown_content = f"""---
layout: post
title: "{article_title}"
date: {today_date}
image: {image_url}
---

![Header Image]({image_url})

{article_text}
"""

with open(filename, 'w', encoding='utf-8') as file:
    file.write(markdown_content)

print(f"Successfully created {filename}")

os.system('git add .')
os.system('git commit -m "Auto-published new article"')
os.system('git push origin main')
